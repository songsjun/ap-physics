def main() -> None:
    with CONTENT_LIBRARY.open(encoding="utf-8") as f:
        library = json.load(f)
    with QUIZ_BANK.open(encoding="utf-8") as f:
        quiz_bank: list[dict] = json.load(f)

    existing_feynman_concepts: set[str] = set()
    for q in quiz_bank:
        if q.get("type") == "feynman":
            for cid in q.get("concept_ids", []):
                existing_feynman_concepts.add(cid)

    concepts = library["concepts"]
    new_questions: list[dict] = []
    missing_concepts: list[str] = []

    for concept in concepts:
        cid = concept["id"]
        if cid in existing_feynman_concepts:
            continue
        if cid not in FEYNMAN:
            missing_concepts.append(cid)
            continue
        question_text, answer, rubric, explanation = FEYNMAN[cid]
        # Derive a short slug from the cid for the question id
        slug = cid
        new_q = {
            "id": f"feynman-{slug}-001",
            "concept_ids": [cid],
            "week": concept["week"],
            "difficulty": 2,
            "type": "feynman",
            "question": question_text,
            "answer": answer,
            "grading_rubric": rubric,
            "explanation": explanation,
        }
        new_questions.append(new_q)

    if missing_concepts:
        raise RuntimeError(
            f"Missing Feynman question definitions for concepts: {missing_concepts}"
        )

    quiz_bank.extend(new_questions)

    with QUIZ_BANK.open("w", encoding="utf-8") as f:
        json.dump(quiz_bank, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Generated {len(new_questions)} feynman questions:")
    for q in new_questions:
        print(f"  {q['id']} (week {q['week']})")


if __name__ == "__main__":
    main()
